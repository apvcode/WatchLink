const DICT: Record<Language, Record<Key, string>> = { en, ru };

export type T = (key: Key, vars?: Record<string, string>) => string;

export function makeT(lang: Language): T {
  return (key, vars) => {
    let text = DICT[lang][key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, v);
    return text;
  };
}

export function getInitialLanguage(): Language {
  try {
    const stored = localStorage.getItem('watchlink:language');
    if (stored === 'ru' || stored === 'en') return stored;
  } catch {}
  const lang = (typeof navigator !== 'undefined' && navigator.language?.toLowerCase()) || '';
  return /^(ru|be|uk)/.test(lang) ? 'ru' : 'en';
}

